create table public.students (
  id bigint generated by default as identity not null,
  student_name text not null,
  usn text not null,
  course text not null,
  study_year text not null,
  gender text not null,
  created_at timestamp with time zone not null default now(),
  phone_number text null,
  constraint students_pkey primary key (id),
  constraint students_usn_key unique (usn),
  constraint students_course_check check (
    course = any (array['BCA', 'BCom', 'BCom Evening', 'BSALP', 'PUC']::text[])
  ),
  constraint students_usn_check check (
    char_length(usn) between 1 and 40
    and usn = upper(btrim(usn))
  ),
  constraint students_year_matches_course check (
    (
      course = 'PUC'
      and study_year = any (array['PUC 1st Year', 'PUC 2nd Year']::text[])
    )
    or (
      course <> 'PUC'
      and study_year = any (array['1st Year', '2nd Year', '3rd Year']::text[])
    )
  ),
  constraint students_student_name_check check (
    char_length(btrim(student_name)) between 1 and 100
  ),
  constraint students_gender_check check (
    gender = any (array['Male', 'Female']::text[])
  )
);

create table public.sports_day_admins (
  user_id uuid not null,
  created_at timestamp with time zone not null default now(),
  constraint sports_day_admins_pkey primary key (user_id),
  constraint sports_day_admins_user_id_fkey
    foreign key (user_id) references auth.users (id) on delete cascade
);

create table public.submission_rate_limits (
  user_id uuid not null,
  last_submission timestamp with time zone not null,
  constraint submission_rate_limits_pkey primary key (user_id)
);

create table public.student_events (
  student_id bigint not null,
  event_name text not null,
  constraint student_events_pkey primary key (student_id, event_name),
  constraint student_events_student_id_fkey
    foreign key (student_id) references public.students (id) on delete cascade,
  constraint student_events_event_name_check check (
    event_name = any (
      array[
        '100m', '200m', '400m', '800m',
        'Long Jump', 'High Jump', 'Discus Throw', 'Shot Put'
      ]::text[]
    )
  )
);

create index if not exists student_events_event_name_idx
  on public.student_events using btree (event_name);