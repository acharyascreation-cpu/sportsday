create table if not exists public.students (
    id bigint generated by default as identity primary key,
    student_name text not null check (char_length(btrim(student_name)) between 1 and 100),
    usn text not null unique check (char_length(usn) between 1 and 40 and usn = upper(btrim(usn))),
    course text not null check (course in ('BCA', 'BCom', 'BCom Evening', 'BSALP', 'PUC')),
    study_year text not null,
    gender text not null check (gender in ('Male', 'Female')),
    created_at timestamptz not null default now(),
    constraint students_year_matches_course check (
        (course = 'PUC' and study_year in ('PUC 1st Year', 'PUC 2nd Year'))
        or
        (course <> 'PUC' and study_year in ('1st Year', '2nd Year', '3rd Year'))
    )
);

create table if not exists public.student_events (
    student_id bigint not null references public.students(id) on delete cascade,
    event_name text not null check (event_name in (
        '100m', '200m', '400m', '800m',
        'Long Jump', 'High Jump', 'Discus Throw', 'Shot Put'
    )),
    primary key (student_id, event_name)
);

create index if not exists student_events_event_name_idx
    on public.student_events (event_name);

create table if not exists public.sports_day_admins (
    user_id uuid primary key references auth.users(id) on delete cascade,
    created_at timestamptz not null default now()
);

alter table public.students enable row level security;
alter table public.student_events enable row level security;
alter table public.sports_day_admins enable row level security;

revoke all on table public.students, public.student_events, public.sports_day_admins
    from public, anon, authenticated;
grant usage on schema public to anon, authenticated;
grant select on table public.students, public.student_events, public.sports_day_admins
    to authenticated;

create or replace function public.is_sports_day_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
    select exists (
        select 1
        from public.sports_day_admins
        where user_id = (select auth.uid())
    );
$$;

drop policy if exists "admins can read students" on public.students;
create policy "admins can read students"
    on public.students for select to authenticated
    using ((select public.is_sports_day_admin()));

drop policy if exists "admins can read student events" on public.student_events;
create policy "admins can read student events"
    on public.student_events for select to authenticated
    using ((select public.is_sports_day_admin()));

drop policy if exists "admins can read own membership" on public.sports_day_admins;
create policy "admins can read own membership"
    on public.sports_day_admins for select to authenticated
    using (user_id = (select auth.uid()));

revoke execute on function public.is_sports_day_admin() from public, anon, authenticated;
grant execute on function public.is_sports_day_admin() to authenticated;

